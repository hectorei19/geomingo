/* ---- dealing a game: six rounds, each with one lie and five truths, no country twice in a game ----
   A round: {m:'lie', set: six codes, c: the liar, s: the six sentences and n: their notes (in the order of set)}.
   The sentences are copied into the round, so a saved game keeps them even if the bank changes. */
const LIES_FROM='2026-11-15';   // the first daily game of "Who's lying?" (bump to the day after the merge)
const LB=LIES_BANK.map((e,i)=>({i,c:e[0],h:e[1],g:e[2],t:e[3],n:e[4],d:e[5]||LIES_FROM}));
// use: {lie index: day number last used} and the same for truths; r: random numbers; key: the day (null = any day)
function dealLies(r,key,use){use=use||{lie:{},tru:{}};const ok=e=>!key||e.d<=key;
  // least used first, ties in random order (a random number per entry, so one shuffle decides)
  const order=(list,last)=>list.map(e=>[e,last[e.i]==null?-1:last[e.i],r()]).sort((a,b)=>a[1]-b[1]||a[2]-b[2]).map(x=>x[0]);
  const usedC=new Set(),dayG=new Set(),lies=[];
  for(const e of order(LB.filter(e=>e.h&&ok(e)),use.lie)){if(lies.length===ROUNDS_LIES)break;
    if(usedC.has(e.c)||dayG.has(e.g))continue;lies.push(e);usedC.add(e.c);dayG.add(e.g)}
  // easy lies first, the hardest last
  lies.sort((a,b)=>a.h-b.h);
  const truths=order(LB.filter(e=>!e.h&&ok(e)),use.tru),rounds=[];
  for(const L of lies){const g=new Set([L.g]),five=[];
    for(const e of truths){if(five.length===5)break;if(usedC.has(e.c)||g.has(e.g))continue;five.push(e);usedC.add(e.c);g.add(e.g)}
    if(five.length<5)return null;
    const all=shuffle(five.concat(L),r);
    rounds.push({m:'lie',set:all.map(e=>e.c),c:L.c,s:all.map(e=>e.t),n:all.map(e=>e.n),ids:all.map(e=>e.i)})}
  return {rounds}}
const ROUNDS_LIES=6;
// the daily games are dealt one after the other from LIES_FROM, so each day takes the sentences used longest ago
